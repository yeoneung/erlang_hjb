#!/usr/bin/env python
"""Render saved numerical data as six tables and three 119 mm figures."""
from pathlib import Path
import json

import numpy as np
from matplotlib.ticker import MaxNLocator
import run_numerics as num
import run_validation as validation_runner

HERE = Path(__file__).resolve().parent
OUT = HERE / "output" / "rendered"
WIDTH = 119 / 25.4


def table(name, alignment, header, rows):
    text = "\n".join([rf"\begin{{tabular}}{{{alignment}}}", r"\toprule",
                      header + r" \\", r"\midrule",
                      *[" & ".join(row) + r" \\" for row in rows],
                      r"\bottomrule", r"\end{tabular}"]) + "\n"
    (OUT / name).write_text(text, encoding="utf-8")


def tables(data, validation):
    table("table_sweep.tex", "rrrrrrr",
          r"$n$ & $W$ & $\tau^*$ & $V$ & $(W-V)/W$ & $S(\tau^*)/S_c$ & $\max Y$",
          [[str(r['n']), f"{r['W']:.3f}", f"{r['tau']:.3f}", f"{r['V']:.3f}",
            f"{100*r['rel_gain']:.1f}\\%", f"{r['S_switch_over_Sc']:.2f}",
            f"{r['after']['max_Y']:.4f}"] for r in data['sweep']])
    table("table_cases.tex", "rrrrrrrr",
          r"$n$ & $\beta$ & $\gamma$ & $W$ & $\tau^*$ & $V$ & $(W-V)/W$ & $S(\tau^*)/S_c$",
          [[str(r['n']), f"{r['beta']:.4f}", f"{r['gamma']:.4f}", f"{r['W']:.3f}",
            f"{r['tau']:.3f}", f"{r['V']:.3f}", f"{100*r['rel_gain']:.1f}\\%",
            f"{r['S_switch_over_Sc']:.2f}"] for r in data['cases']])
    # Use compact headings at the configured figure width.
    (OUT / "table_pmp.tex").write_text(
        num.table_pmp(data['cases']).replace("identity residual", "identity"), encoding="utf-8")
    (OUT / "table_ytarget.tex").write_text(
        num.table_ytarget(data['cases']).replace("after entry", "").replace("$Q$ at entry", "$Q(T)$"),
        encoding="utf-8")
    for name in ("table_convergence.tex", "table_initial_profiles.tex"):
        # These are generated by run_validation.py, without wide redundant columns.
        (OUT / name).write_bytes((HERE / "output" / name).read_bytes())


def axes_pair():
    fig, axes = num.plt.subplots(1, 2, figsize=(WIDTH, 2.12), constrained_layout=True)
    for ax in axes:
        num.style_axis(ax)
        ax.tick_params(labelsize=7)
        ax.xaxis.set_major_locator(MaxNLocator(4))
        ax.yaxis.set_major_locator(MaxNLocator(5))
    return fig, axes


def save(fig, name):
    for ext in ("pdf", "png"):
        fig.savefig(OUT / f"{name}.{ext}", dpi=240)
    num.plt.close(fig)


def figures(data, validation):
    num.plt.rcParams.update({"font.family": "serif", "font.size": 8,
                            "axes.titlesize": 8, "mathtext.fontset": "cm"})
    fig, axes = axes_pair()
    selections = [[next(r for r in data['sweep'] if r['n'] == n) for n in num.SWEEP_PLOT_N],
                  data['cases']]
    for ax, rows, title in zip(axes, selections, ("(a) Fixed parameters", "(b) Selected parameters")):
        colors = num.BLUE_RAMP if len(rows) == 5 else [num.BLUE_RAMP[i] for i in (0, 2, 3, 4)]
        for row, color in zip(rows, colors):
            ax.plot(row['grid'], np.array(row['vals']) - row['W'], color=color,
                    linewidth=1.15, label=rf"$n={row['n']}$")
            ax.plot(row['tau'], row['V'] - row['W'], 'o', color=color, markersize=3)
        ax.axhline(0, color=num.TEXT2_C, linewidth=.5)
        ax.set_xlabel(r"switching time $\tau$")
        ax.set_title(title)
        ax.legend(frameon=False, fontsize=6.5, loc='best', handlelength=1.5)
    axes[0].set_ylabel(r"$T(\tau)-W(z_0)$")
    save(fig, "fig_switch_curves")

    fig, axes = axes_pair()
    for ax, row, tag in zip(axes, (data['cases'][0], data['cases'][-1]), ('(a)', '(b)')):
        p = row['pmp']
        for key, color, label in (('psi', num.BLUE, r'$\psi=-Sp_S$'), ('p1', num.ORANGE, r'$p_1$')):
            values = np.array(p['series'][key])
            ax.plot(p['series']['t'], values / np.max(abs(values)), color=color,
                    linewidth=1.2, label=label)
        ax.axhline(0, color=num.TEXT2_C, linewidth=.5)
        ax.axvline(row['tau'], color=num.TEXT2_C, linewidth=.7, linestyle=':')
        ax.set(xlabel='$t$', ylim=(-1.15, 1.15), title=rf"{tag} $n={row['n']}$")
    axes[0].set_ylabel('normalized adjoints')
    axes[0].legend(frameon=False, fontsize=6.5, loc='lower left')
    save(fig, "fig_pmp")

    fig, axes = axes_pair()
    row = validation['suppression']
    for ax, q, title in zip(axes, ('Y', 'Q'), ('(a) Total infection', '(b) Weighted burden')):
        ax.plot(row['t'], np.array(row[f'off_{q}']) / num.EPS, color=num.ORANGE,
                linewidth=1.2, label='Stop at Y-target')
        ax.plot(row['t'], np.array(row[f'full_then_off_{q}']) / num.EPS, color=num.BLUE,
                linewidth=1.2, label='Stop at Q-target')
        ax.axhline(1, color=num.TEXT2_C, linewidth=.6, linestyle='--')
        ax.axvline(row['Q_entry_time'], color=num.TEXT2_C, linewidth=.7, linestyle=':')
        ax.set(xlim=(0, row['horizon']), xlabel='time', ylabel=rf'${q}/\varepsilon$', title=title)
    axes[1].legend(frameon=False, fontsize=6.3, loc='upper right', handlelength=1.5)
    save(fig, "fig_target_suppression")


if __name__ == '__main__':
    OUT.mkdir(parents=True, exist_ok=True)
    inputs = [HERE / 'output' / name for name in ('results.json', 'validation_results.json')]
    before = {p.name: p.read_bytes() for p in inputs}
    data, validation = [json.loads(p.read_text(encoding='utf-8')) for p in inputs]
    validation_runner.render(validation)
    tables(data, validation)
    figures(data, validation)
    assert before == {p.name: p.read_bytes() for p in inputs}
    print('Rendered 6 tables and 3 figures in output/rendered; numerical data unchanged.')
